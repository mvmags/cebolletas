import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const galleryRoot = path.join(repositoryRoot, "copal", "assets", "gallery");
const outputPath = path.join(repositoryRoot, "copal", "gallery-manifest.js");
const imagePattern = /^image-(\d{4})\.(?:avif|jpe?g|png|webp)$/i;

const folders = (await readdir(galleryRoot, { withFileTypes: true }))
  .filter(entry => entry.isDirectory())
  .map(entry => entry.name)
  .sort();

const manifest = {};

for (const folder of folders) {
  const files = (await readdir(path.join(galleryRoot, folder), { withFileTypes: true }))
    .filter(entry => entry.isFile() && imagePattern.test(entry.name))
    .map(entry => ({
      name: entry.name,
      number: Number(entry.name.match(imagePattern)[1])
    }))
    .sort((a, b) => a.number - b.number);

  files.forEach((file, index) => {
    const expected = index + 1;
    if (file.number !== expected) {
      throw new Error(
        `${folder}: expected image-${String(expected).padStart(4, "0")}, found ${file.name}`
      );
    }
  });

  if (files.length === 0) {
    throw new Error(`${folder}: no image-xxxx files found`);
  }

  manifest[folder] = files.map(file => file.name);
}

const output = `// Generated by scripts/generate-gallery-manifest.mjs. Do not edit.\n` +
  `window.galleryImageManifest = ${JSON.stringify(manifest, null, 2)};\n`;

await writeFile(outputPath, output, "utf8");
console.log(`Generated ${path.relative(repositoryRoot, outputPath)} with ${folders.length} sections.`);
