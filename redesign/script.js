function sectionImage(name, alt = "") {
  return `<div class="feature-media"><img src="./images/${name}" alt="${alt}"></div>`;
}

function renderNav() {
  const t = content[lang];
  nav.innerHTML = Object.entries(t.nav).map(([id, label]) => `<a href="#${id}" data-section="${id}" class="${id === activeSection ? "active" : ""}">${label}</a>`).join("");
  menuButton.setAttribute("aria-label", t.menu);
  document.querySelectorAll("[data-lang]").forEach(button => button.classList.toggle("active", button.dataset.lang === lang));
}

