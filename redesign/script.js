function observeSections() {
  observer?.disconnect();
  observer = new IntersectionObserver(entries => {
    const visible = entries.filter(entry => entry.isIntersecting).sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
    if (!visible) return;
    activeSection = visible.target.id;
    nav.querySelectorAll("a").forEach(link => link.classList.toggle("active", link.dataset.section === activeSection));
    history.replaceState(null, "", `#${activeSection}`);
  }, { root: region, rootMargin: "-22% 0px -55% 0px", threshold: [0, .1, .3, .5] });
  region.querySelectorAll(":scope > section[id]").forEach(section => observer.observe(section));
}

function scrollToHash(behavior = "smooth") {
  const id = location.hash.slice(1) || "intro";
  region.querySelector(`#${CSS.escape(id)}`)?.scrollIntoView({ behavior, block: "start" });
}

function bindDynamicEvents() {
  region.querySelectorAll("a[href^='#']").forEach(link => link.addEventListener("click", event => {
    event.preventDefault(); history.pushState(null, "", link.hash); scrollToHash();
  }));
  region.querySelectorAll(".faq-item button").forEach(button => button.addEventListener("click", () => {
    const item = button.closest(".faq-item");
    item.classList.toggle("open");
    button.setAttribute("aria-expanded", item.classList.contains("open"));
  }));
  region.querySelectorAll("[data-contact]").forEach(button => button.addEventListener("click", () => sendContact(button.dataset.contact)));
}

